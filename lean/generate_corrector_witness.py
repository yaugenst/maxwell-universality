"""Propose six exact dyadic correctors without modifying canonical evidence.

Matches verify_inversion_feshbach_curvature.py: each floating corrector is
divided by pi/20, quantized at 100 bits, then projected to odd parity. Integer
images are proposals; separate Lean kernel proofs verify the actual action.
"""
from hashlib import sha256
import importlib.util
import json
import math
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / "certificates/yee/results/defects"
OUT = ROOT / "Maxwell/Certificate/CorrectorWitness"


def vector(values):
    return "![" + ", ".join(values) + "]"


def emit_table(name, values):
    source = ["-- Generated by generate_corrector_witness.py; proposed exact integer data.",
              "import Maxwell.Certificate.IntegerAction\n",
              "namespace Maxwell.Certificate.CorrectorWitness\n",
              "open Maxwell.Spectral.PrimitiveYee\n",
              "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n"]
    for d in range(3):
        for x in range(20):
            rows = [vector([str(int(values[d * 2000 + x * 100 + y * 10 + z]))
                            for z in range(10)]) for y in range(10)]
            source.append(f"def {name}_{d}_{x} : Fin 10 → Fin 10 → ℤ := {vector(rows)}\n")
    rows = [vector([f"{name}_{d}_{x}" for x in range(20)]) for d in range(3)]
    source.append(f"def {name} (e : Electric) : ℤ := ({vector(rows)}) e.1 e.2.1 e.2.2.1 e.2.2.2\n")
    source.append("end Maxwell.Certificate.CorrectorWitness\n")
    path = OUT / f"{name.title()}.lean"
    path.write_text("\n".join(source))
    return {"name": name, "module": path.stem, "source_sha256": sha256(path.read_bytes()).hexdigest()}


def load_witnesses():
    """Read proposals for other proof generators, without writing any files."""
    spec = importlib.util.spec_from_file_location("corrector_exact_arithmetic", SOURCE / "exact_edge_arithmetic.py")
    arithmetic = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(arithmetic)
    material = json.loads((SOURCE / "inversion_edge_material.json").read_text())
    assert material["period"] == 20 and material["perturbation_denominator"] == 2**21
    perturb = material["full_conventional_perturbation_numerators"]
    model = arithmetic.ExactFiber((1, 1, 0), perturb)
    with np.load(SOURCE / "explore_inversion_edge_feshbach.npz", allow_pickle=False) as data:
        assert tuple(data["k_twice"]) == (1, 1, 0)
        assert int(data["pair_parity"]) == 1
        assert data["perturbation_numerators"].tolist() == perturb
        solutions = data["inversion_perturbed_complement_solutions"]
        assert solutions.shape == (6000, 6) and np.isfinite(solutions).all()
        proposals = [model.project(arithmetic.quantize(np.imag(solutions[:, j]) / (math.pi / 20)), -1)
                     for j in range(6)]
    images = [model.apply_mass_scaled(v) for v in proposals]
    return model, proposals, images


def main():
    OUT.mkdir(exist_ok=True)
    inputs = [SOURCE / name for name in ["exact_edge_arithmetic.py", "inversion_edge_material.json",
              "explore_inversion_edge_feshbach.npz", "verify_inversion_feshbach_curvature.py"]]
    hashes = {str(p): sha256(p.read_bytes()).hexdigest() for p in inputs}
    model, proposals, images = load_witnesses()
    tables = []
    for j in range(6):
        assert model.invert(proposals[j]) == [-x for x in proposals[j]]
        tables.append(emit_table(f"numerator{j}", proposals[j]))
        tables.append(emit_table(f"imageNumerator{j}", images[j]))
    for path, expected in hashes.items():
        assert sha256(Path(path).read_bytes()).hexdigest() == expected
    manifest = {"canonical_sha256": hashes, "tables": tables, "columns": 6,
                "coordinates_per_column": 6000, "numerator_denominator_power": 101,
                "image_denominator_power": 130, "column_order": "j=2*derivative_axis+cluster_column",
                "momentum": [1, 1, 0], "parity": -1,
                "formula": "project(quantize(imag(complement_solutions[:,j])/(math.pi/20), bits=100), -1)",
                "scope": "Proposed literal data only; action, parity, and analytic bounds need Lean proofs."}
    (ROOT / "evidence/corrector_witness_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("Generated six corrector numerator/image pairs; canonical evidence unchanged.")


if __name__ == "__main__":
    main()
