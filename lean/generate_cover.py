"""Emit exact frozen cover data and 64 independently kernel-checked subtrees.

The generator proposes only data. Lean checks inherited boxes at matrix leaves
and exact empty/Gamma/local predicates, then proves coverage of all real points.
"""
from collections import Counter
from fractions import Fraction as Q
from hashlib import sha256
from itertools import product
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PROPOSAL = ROOT.parent / "certificates/yee/work/bulk/global_certificate/cover_proposals.json"
OUT = ROOT / "Maxwell/Certificate"


def key(center, halfwidth, depth):
    assert isinstance(depth, int) and 0 <= depth <= 30
    half = Q(halfwidth)
    assert half == Q(1, 2 ** (depth + 1))
    index = tuple((Q(c) - half) * 2**depth for c in center)
    assert len(index) == 3 and all(i.denominator == 1 and 0 <= i < 2**depth for i in index)
    return depth, tuple(map(int, index))


def endpoints(k):
    depth, index = k
    return tuple(Q(i, 2**depth) for i in index), tuple(Q(i + 1, 2**depth) for i in index)


def empty_wedge(k):
    lo, hi = endpoints(k)
    greedy = (max(lo), max(lo[1:]), lo[2])
    return any(a < b for a, b in zip(hi, greedy)) or sum(greedy) > Q(3, 2)


def local_ball(k):
    lo, hi = endpoints(k)
    return sum(max((a - Q(1, 2)) ** 2, (b - Q(1, 2)) ** 2) for a, b in zip(lo, hi)) <= Q(1, 400)


def rat(q):
    return str(q.numerator) if q.denominator == 1 else f"({q.numerator} / {q.denominator})"


def box(k):
    lo, hi = endpoints(k)
    return "⟨![" + ", ".join(map(rat, lo)) + "], ![" + ", ".join(map(rat, hi)) + "]⟩"


def lookup(lo, hi):
    if hi - lo == 1:
        return f"matrixBox{lo:04d}"
    mid = (lo + hi) // 2
    return f"(if i < {mid} then {lookup(lo, mid)} else {lookup(mid, hi)})"


def main():
    raw = PROPOSAL.read_bytes()
    data = json.loads(raw)
    assert len(data["accepted"]) == 2056 and len(data["excluded_L_boxes"]) == 660
    assert len(data["analytic_gamma_boxes"]) == 1 and not data["pending"]
    leaves, matrix_keys, identities = {}, [], []
    for i, record in enumerate(data["accepted"]):
        k = key(record["center"], record["halfwidth"], record["depth"])
        assert k not in leaves
        leaves[k] = i + 3
        matrix_keys.append(k)
        identities.append({"index": i, "tag": i + 3, "depth": k[0], "dyadic_index": k[1],
                           "witness": record["witness"], "lo": list(map(str, endpoints(k)[0])),
                           "hi": list(map(str, endpoints(k)[1]))})
    for field, tag in (("excluded_L_boxes", 2), ("analytic_gamma_boxes", 1)):
        for center, halfwidth, depth in data[field]:
            k = key(center, halfwidth, depth)
            assert k not in leaves
            assert local_ball(k) if tag == 2 else max(endpoints(k)[1]) <= Q(1, 8)
            leaves[k] = tag
    ancestors = set()
    for depth, index in leaves:
        for a in range(depth):
            ancestor = (a, tuple(i >> (depth - a) for i in index))
            assert ancestor not in leaves
            ancestors.add(ancestor)

    header = ("-- Generated by generate_cover.py from the immutable canonical proposal.\n"
              f"-- Proposal SHA-256: {sha256(raw).hexdigest()}\n")
    definitions = "\n".join(f"def matrixBox{i:04d} : Box := {box(k)}" for i, k in enumerate(matrix_keys))
    (OUT / "CoverData.lean").write_text(header + "import Maxwell.Certificate.CoverSemantics\n\n"
        "namespace Maxwell.Certificate.FrozenCover\n\n" + definitions + "\n\n"
        "private def matrixBoxLookup (i : Nat) : Box :=\n  " + lookup(0, 2056) + "\n\n"
        "/-- The exact 2056 boxes in canonical accepted-record order. -/\n"
        "def matrixBoxes (i : Fin 2056) : Box := matrixBoxLookup i.val\n\n"
        "end Maxwell.Certificate.FrozenCover\n")

    seen, total, chunks = set(), Counter(), []

    def tree(k, counts):
        if empty_wedge(k):
            counts["empty"] += 1
            return "(.leaf 0)"
        if k in leaves:
            tag = leaves[k]
            seen.add(k)
            counts["matrix" if tag >= 3 else "local" if tag == 2 else "gamma"] += 1
            return f"(.leaf {tag})"
        assert k in ancestors, ("Uncovered nonempty box", k)
        counts["octree_internal"] += 1
        depth, index = k
        middle = tuple(Q(2 * i + 1, 2 ** (depth + 1)) for i in index)
        children = {bits: tree((depth + 1, tuple(2 * i + b for i, b in zip(index, bits))), counts)
                    for bits in product(range(2), repeat=3)}

        def split(axis, prefix):
            if axis == 3:
                return children[prefix]
            return (f"(.split {axis} {rat(middle[axis])}\n"
                    f"  {split(axis + 1, prefix + (0,))}\n"
                    f"  {split(axis + 1, prefix + (1,))})")
        return split(0, ())

    for indices in product(range(4), repeat=3):
        name = "".join(map(str, indices))
        counts = Counter()
        proposal = tree((2, indices), counts)
        total.update(counts)
        source = (header + "import Maxwell.Certificate.CoverData\n"
                  "import Maxwell.Certificate.CoverPartition\n\n"
                  "namespace Maxwell.Certificate.FrozenCover\n\n"
                  "set_option maxRecDepth 8192\nset_option maxHeartbeats 0\n\n"
                  f"def tree{name} : CoverTree :=\n  {proposal}\n\n"
                  f"theorem checked{name} : (tree{name}).check (leafCheck matrixBoxes)\n"
                  f"    (quarterBox {indices[0]} {indices[1]} {indices[2]}) = true := by decide +kernel\n\n"
                  f"theorem covers{name} (x : Fin 3 → ℝ)\n"
                  f"    (hx : (quarterBox {indices[0]} {indices[1]} {indices[2]}).Contains x)\n"
                  "    (hw : Box.Wedge x) : Region matrixBoxes x :=\n"
                  f"  check_sound matrixBoxes tree{name} _ checked{name} x hx hw\n\n"
                  "end Maxwell.Certificate.FrozenCover\n")
        path = OUT / f"CoverDataCube{name}.lean"
        path.write_text(source)
        chunks.append({"name": name, "indices": indices, "counts": dict(counts),
                       "source_bytes": len(source.encode()), "source_sha256": sha256(source.encode()).hexdigest()})
    assert seen == set(leaves), {"missing": list(set(leaves) - seen)}
    assert total["matrix"] == 2056 and total["local"] == 660 and total["gamma"] == 1
    final = header + "\n".join(f"import Maxwell.Certificate.CoverDataCube{c['name']}" for c in chunks)
    final += ("\n\nnamespace Maxwell.Certificate.FrozenCover\n\n"
              "/-- Every real point of the root ordered wedge lies in one of the\n"
              "three actual accepted geometric regions. Shared faces are included. -/\n"
              "theorem coverage (x : Fin 3 → ℝ)\n"
              "    (hx : ∀ i, 0 ≤ x i ∧ x i ≤ 1) (hw : Box.Wedge x) :\n"
              "    Gamma x ∨ Box.LocalBall x ∨ ∃ i : Fin 2056, (matrixBoxes i).Contains x := by\n"
              "  have hr : rootBox.Contains x := by\n"
              "    intro i\n"
              "    fin_cases i <;> simpa [rootBox] using hx _\n"
              "  obtain ⟨ix, iy, iz, hq⟩ := root_to_quarters hr\n"
              "  fin_cases ix <;> fin_cases iy <;> fin_cases iz\n")
    final += "\n".join(f"  · exact covers{c['name']} x hq hw" for c in chunks)
    final += "\n\nend Maxwell.Certificate.FrozenCover\n"
    (OUT / "CoverDataComplete.lean").write_text(final)
    assert PROPOSAL.read_bytes() == raw
    (ROOT / "evidence/cover_data_manifest.json").write_text(json.dumps({
        "canonical_proposal": str(PROPOSAL), "canonical_proposal_sha256": sha256(raw).hexdigest(),
        "scope": "Exact geometry only. Matrix spectral acceptance is a separate proof obligation.",
        "matrix_count": 2056, "local_leaf_count": 660, "gamma_leaf_count": 1,
        "generated_counts": dict(total), "matrix_identities": identities, "chunks": chunks,
        "kernel_check": "Each chunk theorem uses decide +kernel; no native_decide. Coverage follows from checker soundness and exact closed-box partition.",
    }, indent=2) + "\n")
    print(json.dumps({"counts": dict(total), "chunks": 64,
                      "largest_chunks": sorted(chunks, key=lambda c: -c["source_bytes"])[:4]}, indent=2))


if __name__ == "__main__":
    main()
