"""Propose exact Hessian dot products; Lean checks every finite sum."""
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path

from generate_bpoint_witness import load_witnesses as load_point
from generate_corrector_witness import load_witnesses as load_corrector

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "Maxwell/Certificate/CurvatureWitness"


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def vector(values):
    return "![" + ", ".join(values) + "]"


def matrix(values):
    return "!![" + "; ".join(", ".join(row) for row in values) + "]"


def rational(value):
    return f"({value.numerator} / {value.denominator})"


def main():
    OUT.mkdir(exist_ok=True)
    inputs = [ROOT / f"Maxwell/Certificate/PointWitness/Numerator{a}.lean" for a in range(2)]
    inputs += [ROOT / f"Maxwell/Certificate/{namespace}/{kind}{j}.lean"
               for namespace, kind in [("CorrectorWitness", "Numerator"), ("BPointWitness", "Rhs")]
               for j in range(6)]
    source = ROOT.parent / "certificates/yee/results/defects"
    inputs += [source / name for name in ["exact_edge_arithmetic.py", "inversion_edge_material.json",
               "explore_inversion_edge_feshbach.npz", "verify_inversion_feshbach_curvature.py",
               "inversion_feshbach_curvature_acceptance.json"]]
    hashes = {str(p): digest(p) for p in inputs}
    model, u, bu = load_point()
    _, y, _ = load_corrector()
    du = {(i, j, b): [sum(c * u[b][e] for e, c in row.items()) for row in model.D[i][j]]
          for i in range(3) for j in range(i, 3) for b in range(2)}
    def action(rows, v):
        return [sum(c * v[e] for e, c in row.items()) for row in rows]
    ku = [[action(model.K[i], u[a]) for a in range(2)] for i in range(3)]
    lu = [[action(model.L[i], u[a]) for a in range(2)] for i in range(3)]
    cu = [action(model.C, u[a]) for a in range(2)]
    modules, ddot, bydot = [], {}, {}

    def emit(name, text, **metadata):
        path = OUT / f"{name}.lean"
        path.write_text(text)
        modules.append({"module": name, "source_sha256": digest(path), **metadata})

    def emit_dot(name, theorem, imports, left, right, v, w, extra="", split=False, actual=None):
        blocks = [[sum(v[e] * w[e] for e in range(d * 2000 + x * 100, d * 2000 + (x + 1) * 100))
                   for x in range(20)] for d in range(3)]
        total = sum(sum(row) for row in blocks)
        values = vector([vector([str(z) for z in row]) for row in blocks])
        prefix = "-- Generated by generate_curvature_witness.py; exact finite dot-product proposal.\n"
        headers = "\n".join(f"import {imp}" for imp in imports)
        headers += "\nimport Maxwell.Certificate.CurvatureWitness.Defs\n\n"
        if actual:
            headers += "import Maxwell.Certificate.CurvatureWitness.Factored\n\n"
        declarations = ("namespace Maxwell.Certificate.CurvatureWitness\n"
                        "open Maxwell.Certificate.PointWitness Maxwell.Certificate.DerivativeBinding\n"
                        "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n")
        text = prefix + headers + declarations
        text += f"def {theorem}Blocks : Fin 3 → Fin 20 → ℤ := {values}\n\n"
        if split:
            emit(f"{name}Data", text + "end Maxwell.Certificate.CurvatureWitness\n", kind="dot_data")
            for d in range(3):
                chunk = prefix + f"import Maxwell.Certificate.CurvatureWitness.{name}Data\n\n" + declarations
                chunk += (f"theorem {theorem}BlocksD{d}_checked (x : Fin 20) :\n"
                          f"    blockDotI {left} {right} {d} x = {theorem}Blocks {d} x := by\n"
                          "  fin_cases x <;> decide +kernel\n\n"
                          "end Maxwell.Certificate.CurvatureWitness\n")
                emit(f"{name}D{d}", chunk, kind="dot_chunk", summands=2000)
            text = prefix + "\n".join(
                f"import Maxwell.Certificate.CurvatureWitness.{name}D{d}" for d in range(3))
            text += "\n\n" + declarations
        block_proof = ("  fin_cases d\n" + "\n".join(
            f"  · exact {theorem}BlocksD{d}_checked x" for d in range(3)) + "\n") if split else (
                "  fin_cases d <;> fin_cases x <;> decide +kernel\n")
        text += (f"theorem {theorem}Blocks_checked (d : Fin 3) (x : Fin 20) :\n"
                 f"    blockDotI {left} {right} d x = {theorem}Blocks d x := by\n"
                 + block_proof + "\n" +
                 f"theorem {theorem}{'_form' if actual else ''}_checked : dotI {left} {right} = {total} := by\n"
                 "  unfold dotI\n"
                 f"  simp_rw [{theorem}Blocks_checked]\n"
                 "  decide +kernel\n\n")
        if actual:
            text += (f"theorem {theorem}_checked : dotI {actual[0]} {actual[1]} = {total} := by\n"
                     f"  rw [dotI_D_form, {theorem}_form_checked]\n\n")
        text += extra.replace("TOTAL", str(total))
        text += "end Maxwell.Certificate.CurvatureWitness\n"
        emit(name, text, kind="dot", summands=6000)
        return total

    for i in range(3):
        for j in range(i, 3):
            for a in range(2):
                for b in range(2):
                    suffix = f"{i}{j}{a}{b}"
                    left = f"PointWitness.numerator{a}"
                    right = f"(DActionI ![1,1,0] {i} {j} PointWitness.numerator{b})"
                    extra = ""
                    if i != j:
                        extra = (f"theorem dotD{j}{i}{a}{b}_checked :\n"
                                 f"    dotI {left} (DActionI ![1,1,0] {j} {i} PointWitness.numerator{b}) = TOTAL := by\n"
                                 f"  have h : DActionI ![1,1,0] {j} {i} PointWitness.numerator{b} =\n"
                                 f"      DActionI ![1,1,0] {i} {j} PointWitness.numerator{b} :=\n"
                                 f"    funext (DActionI_comm ![1,1,0] {j} {i} PointWitness.numerator{b})\n"
                                 f"  rw [h, dotD{suffix}_checked]\n\n")
                    imports = [f"Maxwell.Certificate.PointWitness.Numerator{k}" for k in sorted({a, b})]
                    if suffix == "0000":
                        # Preserve the three complete direct-action chunk proofs from the interrupted run.
                        value = emit_dot(f"DotD{suffix}", f"dotD{suffix}", imports,
                            left, right, u[a], du[i, j, b], extra, split=True)
                    else:
                        form = [ku[i][a][e] * ku[j][b][e] + ku[j][a][e] * ku[i][b][e]
                                - (lu[i][a][e] * cu[b][e] + cu[a][e] * lu[i][b][e] if i == j else 0)
                                for e in range(6000)]
                        assert sum(form) == sum(z * w for z, w in zip(u[a], du[i, j, b]))
                        value = emit_dot(f"DotD{suffix}", f"dotD{suffix}", imports,
                            "(fun _ => 1)", f"(DFormI ![1,1,0] {i} {j} PointWitness.numerator{a} PointWitness.numerator{b})",
                            [1] * 6000, form, extra, split=True, actual=(left, right))
                    ddot[i, j, a, b] = ddot[j, i, a, b] = value
    for p in range(6):
        for q in range(6):
            bydot[p, q] = emit_dot(f"DotBY{p}{q}", f"dotBY{p}{q}",
                [f"Maxwell.Certificate.BPointWitness.Rhs{p}",
                 f"Maxwell.Certificate.CorrectorWitness.Numerator{q}"],
                f"BPointWitness.rhs{p}", f"CorrectorWitness.numerator{q}", bu[p], y[q])
    raw = [[Fraction(ddot[p // 2, q // 2, p % 2, q % 2] - bydot[p, q]
                     - bydot[2 * (q // 2) + p % 2, 2 * (p // 2) + q % 2], 2**202)
            for q in range(6)] for p in range(6)]
    data = ("-- Generated by generate_curvature_witness.py. The dot bindings are separate proofs.\n"
            "import Maxwell.Certificate.FrozenHessian.Data\n"
            "import Mathlib.Analysis.Real.Pi.Bounds\n\n"
            "namespace Maxwell.Certificate.CurvatureWitness\n"
            "noncomputable section\n\n"
            f"def raw : Matrix (Fin 6) (Fin 6) ℚ := {matrix([[rational(x) for x in row] for row in raw])}\n\n"
            "def hessianApprox : Matrix (Fin 6) (Fin 6) ℝ :=\n"
            "  fun p q => Real.pi ^ 2 / 400 * (raw p q : ℝ)\n\n"
            "end\nend Maxwell.Certificate.CurvatureWitness\n")
    emit("Data", data, kind="data")
    bindings = "\n".join(f"import Maxwell.Certificate.CurvatureWitness.{m['module']}"
                         for m in modules if m["kind"] == "dot")
    bindings += "\nimport Maxwell.Certificate.CurvatureWitness.Data\n"
    bindings += "import Maxwell.Certificate.DerivativeAction\nimport Maxwell.Certificate.PointWitness.Inner\n"
    bindings += "\n".join(f"import Maxwell.Certificate.BPointWitness.Action{j}" for j in range(6))
    bindings += "\n\nnamespace Maxwell.Certificate.CurvatureWitness\n"
    bindings += "open Maxwell.Spectral.PrimitiveYee Maxwell.Certificate.PointWitness Maxwell.Certificate.DerivativeBinding\n"
    bindings += "noncomputable section\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
    bindings += "def pointNumerators : Fin 2 → Electric → ℤ := ![PointWitness.numerator0, PointWitness.numerator1]\n"
    bindings += "def correctorNumerators : Fin 3 → Fin 2 → Electric → ℤ := " + vector([
        vector([f"CorrectorWitness.numerator{2 * i + a}" for a in range(2)]) for i in range(3)]) + "\n"
    bindings += "def bNumerators : Fin 3 → Fin 2 → Electric → ℤ := " + vector([
        vector([f"BPointWitness.rhs{2 * i + a}" for a in range(2)]) for i in range(3)]) + "\n\n"
    bindings += """def index (i : Fin 3) (a : Fin 2) : Fin 6 := ⟨2 * i.val + a.val, by omega⟩
def direction (p : Fin 6) : Fin 3 := ⟨p.val / 2, by omega⟩
def column (p : Fin 6) : Fin 2 := ⟨p.val % 2, by omega⟩

theorem index_coordinates (p : Fin 6) : index (direction p) (column p) = p := by
  apply Fin.ext
  dsimp [index, direction, column]
  omega

def coefficientDot (i j : Fin 3) (a b : Fin 2) : ℤ :=
  dotI (pointNumerators a) (DActionI ![1,1,0] i j (pointNumerators b)) -
    dotI (bNumerators i a) (correctorNumerators j b) -
    dotI (bNumerators j a) (correctorNumerators i b)

theorem raw_binding (i j : Fin 3) (a b : Fin 2) :
    raw (index i a) (index j b) = (coefficientDot i j a b : ℚ) / 2 ^ 202 := by
  fin_cases i <;> fin_cases j <;> fin_cases a <;> fin_cases b <;>
    norm_num [raw, index, coefficientDot, pointNumerators, correctorNumerators, bNumerators,
"""
    checks = [f"dotD{i}{j}{a}{b}_checked" for i in range(3) for j in range(3)
              for a in range(2) for b in range(2)]
    checks += [f"dotBY{p}{q}_checked" for p in range(6) for q in range(6)]
    bindings += "      " + ", ".join(checks) + "]\n\n"
    bindings += """theorem bNumerators_action (i : Fin 3) (a : Fin 2) :
    BActionI ![1,1,0] i (pointNumerators a) = bNumerators i a := by
  funext e
  fin_cases i <;> fin_cases a
"""
    bindings += "\n".join(f"  · exact BPointWitness.rhs{j}_action e" for j in range(6)) + "\n\n"
    bindings += """theorem coefficientDot_actual (i j : Fin 3) (a b : Fin 2) :
    coefficientDot i j a b =
      dotI (pointNumerators a) (DActionI ![1,1,0] i j (pointNumerators b)) -
      dotI (BActionI ![1,1,0] i (pointNumerators a)) (correctorNumerators j b) -
      dotI (BActionI ![1,1,0] j (pointNumerators a)) (correctorNumerators i b) := by
  rw [bNumerators_action, bNumerators_action]
  rfl

/-- The literal coefficient is bound to the actual sparse integer derivative
actions, normalized as complex vectors with the frozen denominator. -/
theorem hessianApprox_binding_index (i j : Fin 3) (a b : Fin 2) :
    (hessianApprox (index i a) (index j b) : ℂ) =
      (Real.pi ^ 2 / 400 : ℂ) *
        (inner ℂ (integerVector (pointNumerators a) (2^101))
          (integerVector (DActionI ![1,1,0] i j (pointNumerators b)) (2^101)) -
        inner ℂ (integerVector (BActionI ![1,1,0] i (pointNumerators a)) (2^101))
          (integerVector (correctorNumerators j b) (2^101)) -
        inner ℂ (integerVector (BActionI ![1,1,0] j (pointNumerators a)) (2^101))
          (integerVector (correctorNumerators i b) (2^101))) := by
  unfold hessianApprox
  rw [raw_binding, coefficientDot_actual]
  simp only [integerVector_inner]
  push_cast
  ring

theorem hessianApprox_binding (p q : Fin 6) :
    (hessianApprox p q : ℂ) =
      (Real.pi ^ 2 / 400 : ℂ) *
        (inner ℂ (integerVector (pointNumerators (column p)) (2^101))
          (integerVector (DActionI ![1,1,0] (direction p) (direction q)
            (pointNumerators (column q))) (2^101)) -
        inner ℂ (integerVector (BActionI ![1,1,0] (direction p)
          (pointNumerators (column p))) (2^101))
          (integerVector (correctorNumerators (direction q) (column q)) (2^101)) -
        inner ℂ (integerVector (BActionI ![1,1,0] (direction q)
          (pointNumerators (column p))) (2^101))
          (integerVector (correctorNumerators (direction p) (column q)) (2^101))) := by
  simpa only [index_coordinates] using
    hessianApprox_binding_index (direction p) (direction q) (column p) (column q)

end
end Maxwell.Certificate.CurvatureWitness
"""
    emit("Bindings", bindings, kind="binding")
    complete = """import Maxwell.Certificate.CurvatureWitness.Bindings
import Maxwell.Certificate.CurvatureWitness.Rounding

#print axioms Maxwell.Certificate.CurvatureWitness.hessianApprox_binding
#print axioms Maxwell.Certificate.CurvatureWitness.entry_rounding_error
"""
    emit("Complete", complete, kind="audit")
    for path, expected in hashes.items():
        assert digest(Path(path)) == expected
    manifest = {"input_sha256": hashes, "modules": modules,
                "direct_D_dot_products": 24, "B_Y_dot_products": 36,
                "summands_per_dot_product": 6000, "raw_denominator_power": 202,
                "coefficient": "pi^2/400*(U_a^T D_ij U_b-(B_i U_a)^T Y_jb-(B_j U_a)^T Y_ib)/2^202",
                "raw_rational": [[str(x) for x in row] for row in raw]}
    (ROOT / "evidence/curvature_witness_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("Generated 24 actual D-action dot checks, 36 B/Y dot checks, and the exact raw coefficient matrix.")


if __name__ == "__main__":
    main()
