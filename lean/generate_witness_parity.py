"""Generate complete integer inversion proofs for the eight frozen vectors."""
from hashlib import sha256
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def main():
    prefix = "-- Generated by generate_witness_parity.py; literal tables are unchanged.\n"
    modules, inputs = [], {}

    def emit(namespace, name, source, **metadata):
        path = ROOT / f"Maxwell/Certificate/{namespace}/{name}.lean"
        path.write_text(source)
        modules.append({"namespace": namespace, "module": name,
                        "source_sha256": digest(path), **metadata})

    for namespace, columns, sign in [("PointWitness", 2, 1), ("CorrectorWitness", 6, -1)]:
        for v in range(columns):
            table = ROOT / f"Maxwell/Certificate/{namespace}/Numerator{v}.lean"
            inputs[str(table.relative_to(ROOT))] = digest(table)
            rhs = f"numerator{v}" if sign == 1 else f"-numerator{v}"
            for x in range(20):
                name = f"Parity{v}X{x:02d}"
                source = (prefix + f"import Maxwell.Certificate.{namespace}.Numerator{v}\n"
                          "import Maxwell.Certificate.InversionInteger\n\n"
                          f"namespace Maxwell.Certificate.{namespace}\n"
                          "open Maxwell.Certificate.PrimitiveBinding\n"
                          "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
                          f"theorem parity{v}_{x:02d} (d : Fin 3) (y z : Fin 10) :\n"
                          f"    electricInversionActionI ![1,1,0] numerator{v} (d, ({x}, y, z)) =\n"
                          f"      {rhs} (d, ({x}, y, z)) := by\n"
                          "  fin_cases d <;> fin_cases y <;> fin_cases z <;> decide +kernel\n\n"
                          f"end Maxwell.Certificate.{namespace}\n")
                emit(namespace, name, source, column=v, x=x, entries=300, sign=sign)
            source = prefix + "\n".join(
                f"import Maxwell.Certificate.{namespace}.Parity{v}X{x:02d}" for x in range(20))
            source += (f"\n\nnamespace Maxwell.Certificate.{namespace}\n"
                       "open Maxwell.Certificate.PrimitiveBinding Maxwell.Spectral.PrimitiveYee\n\n"
                       f"/-- The frozen integer vector has exact inversion parity {sign}. -/\n"
                       f"theorem numerator{v}_parity (e : Electric) :\n"
                       f"    electricInversionActionI ![1,1,0] numerator{v} e = {rhs} e := by\n"
                       "  rcases e with ⟨d, x, y, z⟩\n"
                       "  fin_cases x\n")
            source += "\n".join(f"  · exact parity{v}_{x:02d} d y z" for x in range(20))
            source += f"\n\nend Maxwell.Certificate.{namespace}\n"
            emit(namespace, f"Parity{v}Complete", source, column=v, entries=6000, sign=sign)
        source = prefix + "\n".join(
            f"import Maxwell.Certificate.{namespace}.Parity{v}Complete" for v in range(columns))
        source += "\n\n" + "\n".join(
            f"#print axioms Maxwell.Certificate.{namespace}.numerator{v}_parity" for v in range(columns)) + "\n"
        emit(namespace, "ParityComplete", source, entries=6000 * columns, sign=sign)
    for path, expected in inputs.items():
        assert digest(ROOT / path) == expected
    manifest = {
        "scope": "All 48,000 coordinates: two even point vectors and six odd correctors under actual signed staggered electric inversion.",
        "table_sha256": inputs, "modules": modules, "kernel_checks": 48000,
        "chunk_modules": 160, "operator_module": "Maxwell.Certificate.InversionInteger",
        "operator": "Maxwell.Certificate.PrimitiveBinding.electricInversionActionI",
        "momentum": [1, 1, 0], "proof_method": "Finite case splitting and decide +kernel",
    }
    (ROOT / "evidence/witness_parity_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("Generated 160 parity chunks, eight complete column theorems, and two axiom audits.")


if __name__ == "__main__":
    main()
