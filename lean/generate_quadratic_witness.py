"""Propose the exact full quadratic residual vectors and their action proofs."""
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path

from generate_bpoint_witness import load_witnesses as load_point
from generate_corrector_witness import load_witnesses as load_corrector

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "Maxwell/Certificate/QuadraticWitness"
PAIRS = [(i, j, a) for i in range(3) for j in range(i, 3) for a in range(2)]


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def vector(values):
    return "![" + ", ".join(values) + "]"


def load_witnesses():
    """Return model, point columns, correctors, and symmetric Traw data, without writes."""
    model, u, _ = load_point()
    _, y, _ = load_corrector()

    def action(rows, v):
        return [sum(c * v[e] for e, c in row.items()) for row in rows]

    by = {(i, j, a): action(model.B[i], y[2 * j + a])
          for i in range(3) for j in range(3) for a in range(2)}
    traw = {}
    for i, j, a in PAIRS:
        du = action(model.D[i][j], u[a])
        value = [aa + bb + cc for aa, bb, cc in zip(du, by[i, j, a], by[j, i, a])]
        traw[i, j, a] = traw[j, i, a] = value
    return model, u, y, traw


def main():
    OUT.mkdir(exist_ok=True)
    canonical = ROOT.parent / "certificates/yee/results/defects"
    inputs = [canonical / name for name in ["exact_edge_arithmetic.py", "inversion_edge_material.json",
              "explore_inversion_edge_feshbach.npz", "verify_inversion_feshbach_curvature.py"]]
    inputs += [ROOT / f"Maxwell/Certificate/{ns}/Numerator{a}.lean"
               for ns, count in [("PointWitness", 2), ("CorrectorWitness", 6)] for a in range(count)]
    hashes = {str(p): digest(p) for p in inputs}
    _, _, _, traw = load_witnesses()
    modules = []
    prefix = "-- Generated by generate_quadratic_witness.py; exact vector proposal.\n"
    declarations = ("namespace Maxwell.Certificate.QuadraticWitness\n"
                    "open Maxwell.Spectral.PrimitiveYee Maxwell.Certificate.DerivativeBinding\n"
                    "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n")

    def emit(name, source, **metadata):
        path = OUT / f"{name}.lean"
        path.write_text(source)
        modules.append({"module": name, "source_sha256": digest(path), **metadata})

    for i, j, a in PAIRS:
        suffix = f"{i}{j}{a}"
        name = f"numerator{suffix}"
        values = traw[i, j, a]
        source = prefix + "import Maxwell.Certificate.DerivativeInteger\n\n" + declarations
        for d in range(3):
            for x in range(20):
                rows = [vector([str(values[d * 2000 + x * 100 + y * 10 + z]) for z in range(10)])
                        for y in range(10)]
                source += f"def {name}_{d}_{x} : Fin 10 → Fin 10 → ℤ := {vector(rows)}\n"
        rows = [vector([f"{name}_{d}_{x}" for x in range(20)]) for d in range(3)]
        source += f"\ndef {name} (e : Electric) : ℤ := ({vector(rows)}) e.1 e.2.1 e.2.2.1 e.2.2.2\n\n"
        source += "end Maxwell.Certificate.QuadraticWitness\n"
        emit(f"Numerator{suffix}", source, kind="table", coordinates=6000)
        chunks = []
        inputs_import = (f"import Maxwell.Certificate.QuadraticWitness.Numerator{suffix}\n"
                        f"import Maxwell.Certificate.PointWitness.Numerator{a}\n")
        inputs_import += "\n".join(f"import Maxwell.Certificate.CorrectorWitness.Numerator{v}"
                                   for v in sorted({2 * j + a, 2 * i + a})) + "\n\n"
        for d in range(3):
            for x in range(20):
                module = f"Action{suffix}D{d}X{x:02d}"
                chunks.append(module)
                e = f"({d}, ({x}, y, z))"
                source = prefix + inputs_import + declarations
                source += (f"theorem action{suffix}_{d}_{x:02d} (y z : Fin 10) :\n"
                           f"    DActionI ![1,1,0] {i} {j} PointWitness.numerator{a} {e} +\n"
                           f"      BActionI ![1,1,0] {i} CorrectorWitness.numerator{2 * j + a} {e} +\n"
                           f"      BActionI ![1,1,0] {j} CorrectorWitness.numerator{2 * i + a} {e} =\n"
                           f"        {name} {e} := by\n"
                           "  fin_cases y <;> fin_cases z <;> decide +kernel\n\n"
                           "end Maxwell.Certificate.QuadraticWitness\n")
                emit(module, source, kind="action_chunk", coordinates=100)
        source = prefix + "\n".join(f"import Maxwell.Certificate.QuadraticWitness.{m}" for m in chunks)
        source += "\n\n" + declarations
        source += (f"theorem {name}_action (e : Electric) :\n"
                   f"    DActionI ![1,1,0] {i} {j} PointWitness.numerator{a} e +\n"
                   f"      BActionI ![1,1,0] {i} CorrectorWitness.numerator{2 * j + a} e +\n"
                   f"      BActionI ![1,1,0] {j} CorrectorWitness.numerator{2 * i + a} e = {name} e := by\n"
                   "  rcases e with ⟨d, x, y, z⟩\n  fin_cases d <;> fin_cases x\n")
        source += "\n".join(f"  · exact action{suffix}_{d}_{x:02d} y z" for d in range(3) for x in range(20))
        source += "\n\nend Maxwell.Certificate.QuadraticWitness\n"
        emit(f"Action{suffix}Complete", source, kind="action_complete", coordinates=6000)
    source = prefix + "\n".join(
        f"import Maxwell.Certificate.QuadraticWitness.Action{i}{j}{a}Complete" for i, j, a in PAIRS)
    source += "\n\n" + "\n".join(
        f"#print axioms Maxwell.Certificate.QuadraticWitness.numerator{i}{j}{a}_action" for i, j, a in PAIRS) + "\n"
    emit("ActionComplete", source, kind="audit")
    source = prefix + "\n".join(
        f"import Maxwell.Certificate.QuadraticWitness.Numerator{i}{j}{a}" for i, j, a in PAIRS)
    source += "\n\n" + declarations
    source += "def numerators : Fin 3 → Fin 3 → Fin 2 → Electric → ℤ := " + vector([
        vector([vector([f"numerator{min(i,j)}{max(i,j)}{a}" for a in range(2)]) for j in range(3)])
        for i in range(3)]) + "\n\nend Maxwell.Certificate.QuadraticWitness\n"
    emit("Data", source, kind="data")
    rawgram = [[Fraction(sum(sum(aa * bb for aa, bb in zip(traw[i, p // 2, p % 2], traw[i, q // 2, q % 2]))
                            for i in range(3)), 2**204) for q in range(6)] for p in range(6)]
    for path, expected in hashes.items():
        assert digest(Path(path)) == expected
    manifest = {"input_sha256": hashes, "modules": modules, "columns": 12,
                "checked_action_coordinates": 72000, "physical_vector": "theta^2 * integerVector numerator (2^102)",
                "formula": "D_ij U_a + B_i Y_ja + B_j Y_ia, i<=j; symmetric remaining entries",
                "raw_gram": [[str(x) for x in row] for row in rawgram]}
    (ROOT / "evidence/quadratic_witness_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("Generated 12 full-quadratic vectors and 72,000 actual coordinate checks; input data unchanged.")


if __name__ == "__main__":
    main()
