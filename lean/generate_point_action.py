"""Emit kernel proofs for every entry of both actual integer Yee actions.

This generator never rewrites the literal witness tables. Each generated
module checks 100 entries using only one numerator/image pair of imports.
"""
from hashlib import sha256
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--namespace", choices=["PointWitness", "CorrectorWitness"], default="PointWitness")
    args = parser.parse_args()
    namespace = args.namespace
    columns = 2 if namespace == "PointWitness" else 6
    prefix_name = "point" if namespace == "PointWitness" else "corrector"
    out = ROOT / f"Maxwell/Certificate/{namespace}"
    inputs = {str(p.relative_to(ROOT)): sha256(p.read_bytes()).hexdigest()
              for p in [out / f"{kind}{v}.lean"
                        for v in range(columns) for kind in ["Numerator", "Imagenumerator"]]}
    generated = []
    prefix = "-- Generated by generate_point_action.py; literal witness tables are unchanged.\n"
    for v in range(columns):
        names = []
        for d in range(3):
            for x in range(20):
                name = f"Action{v}D{d}X{x:02d}"
                names.append((name, d, x))
                source = (prefix + f"import Maxwell.Certificate.{namespace}.Numerator{v}\n"
                          f"import Maxwell.Certificate.{namespace}.Imagenumerator{v}\n\n"
                          f"namespace Maxwell.Certificate.{namespace}\n"
                          "open Maxwell.Certificate.PrimitiveBinding\n"
                          "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
                          f"theorem action{v}_{d}_{x:02d} (y z : Fin 10) :\n"
                          f"    fiberActionI ![1,1,0] numerator{v} ({d}, ({x}, y, z)) =\n"
                          f"      imageNumerator{v} ({d}, ({x}, y, z)) := by\n"
                          "  fin_cases y <;> fin_cases z <;> decide +kernel\n\n"
                          f"end Maxwell.Certificate.{namespace}\n")
                (out / f"{name}.lean").write_text(source)
                generated.append({"module": name, "column": v, "direction": d, "x": x,
                                  "entries": 100, "source_sha256": sha256(source.encode()).hexdigest()})
        complete = prefix + "\n".join(f"import Maxwell.Certificate.{namespace}.{n}" for n, _, _ in names)
        complete += (f"\n\nnamespace Maxwell.Certificate.{namespace}\n"
                     "open Maxwell.Certificate.PrimitiveBinding Maxwell.Spectral.PrimitiveYee\n\n"
                     f"/-- The actual integer Yee action agrees at all 6000 electric coordinates. -/\n"
                     f"theorem numerator{v}_action (e : Electric) :\n"
                     f"    fiberActionI ![1,1,0] numerator{v} e = imageNumerator{v} e := by\n"
                     "  rcases e with ⟨d, x, y, z⟩\n"
                     "  fin_cases d <;> fin_cases x\n")
        complete += "\n".join(f"  · exact action{v}_{d}_{x:02d} y z" for _, d, x in names)
        complete += f"\n\nend Maxwell.Certificate.{namespace}\n"
        (out / f"Action{v}Complete.lean").write_text(complete)
        generated.append({"module": f"Action{v}Complete", "column": v, "entries": 6000,
                          "source_sha256": sha256(complete.encode()).hexdigest()})
    final = prefix + "\n".join(f"import Maxwell.Certificate.{namespace}.Action{v}Complete" for v in range(columns))
    final += "\n\n" + "\n".join(f"#print axioms Maxwell.Certificate.{namespace}.numerator{v}_action" for v in range(columns)) + "\n"
    (out / "ActionComplete.lean").write_text(final)
    generated.append({"module": "ActionComplete", "entries": 6000 * columns,
                      "source_sha256": sha256(final.encode()).hexdigest()})
    for name, digest in inputs.items():
        assert sha256((ROOT / name).read_bytes()).hexdigest() == digest
    manifest = {"scope": f"Exact actual integer Yee action, {columns} complete 6000-coordinate witness columns",
                "namespace": namespace, "columns": columns,
                "table_sha256": inputs, "modules": generated,
                "kernel_checks": 6000 * columns, "chunk_modules": 60 * columns,
                "proof_method": "Finite case split and decide +kernel; no native_decide"}
    (ROOT / f"evidence/{prefix_name}_action_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated {60 * columns} kernel-check chunks, {columns} column compositions, and the axiom audit.")


if __name__ == "__main__":
    main()
