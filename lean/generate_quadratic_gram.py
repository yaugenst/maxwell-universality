"""Generate exact full quadratic-residual Gram sums and LDL proposals."""
from fractions import Fraction as F
from hashlib import sha256
import json
from pathlib import Path
from generate_quadratic_witness import load_witnesses

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "Maxwell/Certificate/QuadraticWitness"


def vec(values):
    return "![" + ", ".join(values) + "]"


def rat(q):
    q = F(q)
    return str(q.numerator) if q.denominator == 1 else f"({q.numerator} / {q.denominator})"


def mat(values):
    return "!![" + "; ".join(", ".join(rat(x) for x in row) for row in values) + "]"


def canonical(i, p):
    j, a = divmod(p, 2)
    return (min(i, j), max(i, j), a)


def suffix(key):
    return "".join(map(str, key))


def ldl(a):
    n = len(a)
    L, d = [[F(int(i == j)) for j in range(n)] for i in range(n)], []
    for i in range(n):
        d.append(a[i][i] - sum(L[i][k] ** 2 * d[k] for k in range(i)))
        assert d[-1] > 0
        for j in range(i + 1, n):
            L[j][i] = (a[j][i] - sum(L[j][k] * L[i][k] * d[k] for k in range(i))) / d[i]
    assert all(a[i][j] == sum(L[i][k] * d[k] * L[j][k] for k in range(n))
               for i in range(n) for j in range(n))
    return L, d


def main():
    _, _, _, t = load_witnesses()
    action_manifest = ROOT / "evidence/quadratic_witness_manifest.json"
    before = sha256(action_manifest.read_bytes()).hexdigest()
    modules, checks, totals = [], {}, {}
    prefix = "-- Generated by generate_quadratic_gram.py; exact finite Gram proposal.\n"

    def emit(name, text, kind):
        path = OUT / f"{name}.lean"
        path.write_text(text)
        modules.append({"module": name, "source_sha256": sha256(path.read_bytes()).hexdigest(), "kind": kind})

    pairs = sorted({tuple(sorted((canonical(i, p), canonical(i, q))))
                    for i in range(3) for p in range(6) for q in range(p, 6)})
    for left, right in pairs:
        x, y = suffix(left), suffix(right)
        name, theorem = f"Dot{x}_{y}", f"dot{x}_{y}"
        blocks = [[sum(t[left][e] * t[right][e] for e in range(d * 2000 + n * 100, d * 2000 + (n + 1) * 100))
                   for n in range(20)] for d in range(3)]
        total = sum(map(sum, blocks))
        totals[left, right] = totals[right, left] = total
        checks[left, right] = f"{theorem}_checked"
        text = prefix + "\n".join(f"import Maxwell.Certificate.QuadraticWitness.Numerator{z}" for z in sorted({x, y}))
        text += "\nimport Maxwell.Certificate.PointWitness.DotDefs\n\n"
        text += "namespace Maxwell.Certificate.QuadraticWitness\nopen Maxwell.Certificate.PointWitness\n"
        text += "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
        text += f"def {theorem}Blocks : Fin 3 → Fin 20 → ℤ := " + vec([vec([str(z) for z in row]) for row in blocks]) + "\n\n"
        text += (f"theorem {theorem}Blocks_checked (d : Fin 3) (n : Fin 20) :\n"
                 f"    blockDotI numerator{x} numerator{y} d n = {theorem}Blocks d n := by\n"
                 "  fin_cases d <;> fin_cases n <;> decide +kernel\n\n"
                 f"theorem {theorem}_checked : dotI numerator{x} numerator{y} = {total} := by\n"
                 f"  unfold dotI\n  simp_rw [{theorem}Blocks_checked]\n  decide +kernel\n\n")
        if x != y:
            checks[right, left] = f"dot{y}_{x}_checked"
            text += (f"theorem dot{y}_{x}_checked : dotI numerator{y} numerator{x} = {total} := by\n"
                     f"  have h : dotI numerator{y} numerator{x} = dotI numerator{x} numerator{y} := by\n"
                     "    simp only [dotI_eq_sum, mul_comm]\n"
                     f"  rw [h, {theorem}_checked]\n\n")
        text += "end Maxwell.Certificate.QuadraticWitness\n"
        emit(name, text, "dot")
    raw = [[F(sum(totals[canonical(i, p), canonical(i, q)] for i in range(3)), 2**204)
            for q in range(6)] for p in range(6)]
    witness = json.loads(action_manifest.read_text())
    assert raw == [[F(x) for x in row] for row in witness["raw_gram"]]
    alpha = F(314159265358979323847, 10**20) ** 2 / 400
    upper = [[alpha**2 * z for z in row] for row in raw]
    text = (prefix + "import Maxwell.Certificate.CurvatureWitness.Rounding\n\n"
            "namespace Maxwell.Certificate.QuadraticWitness\nnoncomputable section\n\n"
            f"def rawGram : Matrix (Fin 6) (Fin 6) ℝ := {mat(raw)}\n\n"
            "def gramUpper : Matrix (Fin 6) (Fin 6) ℝ :=\n"
            "  CurvatureWitness.alphaUpper ^ 2 • rawGram\n\n"
            "end\nend Maxwell.Certificate.QuadraticWitness\n")
    emit("GramData", text, "data")
    text = prefix + "\n".join(f"import Maxwell.Certificate.QuadraticWitness.{m['module']}" for m in modules if m["kind"] == "dot")
    text += "\nimport Maxwell.Certificate.QuadraticWitness.Data\nimport Maxwell.Certificate.QuadraticWitness.GramData\nimport Maxwell.Certificate.PointWitness.Inner\n\n"
    text += "namespace Maxwell.Certificate.QuadraticWitness\nopen Maxwell.Certificate.PointWitness\nnoncomputable section\n"
    text += "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
    text += """def direction (p : Fin 6) : Fin 3 := ⟨p.val / 2, by omega⟩
def column (p : Fin 6) : Fin 2 := ⟨p.val % 2, by omega⟩
def rawColumn (i : Fin 3) (p : Fin 6) :=
  integerVector (numerators i (direction p) (column p)) (2^102)

theorem rawGram_binding (p q : Fin 6) :
    (∑ i : Fin 3, inner ℂ (rawColumn i p) (rawColumn i q)) = (rawGram p q : ℂ) := by
  simp only [rawColumn, integerVector_inner]
  fin_cases p <;> fin_cases q <;>
    norm_num [direction, column, numerators, rawGram, Fin.sum_univ_three,
"""
    text += "      " + ", ".join(sorted(set(checks.values()))) + "]\n\n"
    text += "end\nend Maxwell.Certificate.QuadraticWitness\n"
    emit("Gram", text, "binding")
    canonical_json = ROOT.parent / "certificates/yee/results/defects/inversion_feshbach_curvature_acceptance.json"
    frozen = [[F(x) for x in row] for row in json.loads(canonical_json.read_text())["rounded_hessian_block"]]
    for name, theorem, target, expression in [
        ("GramNorm", "gram_norm_psd", [[4 * F(i == j) - upper[i][j] for j in range(6)] for i in range(6)],
         "((4 : ℝ) • (1 : Matrix (Fin 6) (Fin 6) ℝ) - gramUpper)"),
        ("GramRelative", "gram_relative_psd", [[F(9, 5) * frozen[i][j] - upper[i][j] - F(i == j, 10000)
                                                for j in range(6)] for i in range(6)],
         "((9/5 : ℝ) • FrozenHessian.lppm - gramUpper - (1/10000 : ℝ) • (1 : Matrix (Fin 6) (Fin 6) ℝ))")]:
        L, d = ldl(target)
        text = prefix + "import Maxwell.Certificate.QuadraticWitness.GramData\n\n"
        text += "namespace Maxwell.Certificate.QuadraticWitness\nopen Matrix\nnoncomputable section\n"
        text += "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
        text += f"private def lower : Matrix (Fin 6) (Fin 6) ℝ := {mat(L)}\n"
        text += f"private def pivots : Fin 6 → ℝ := {vec([rat(z) for z in d])}\n\n"
        text += (f"theorem {theorem} : {expression}.PosSemidef := by\n"
                 "  apply real_ldl_sound _ lower pivots\n"
                 "  · ext i j\n    simp only [ldl_apply]\n"
                 "    fin_cases i <;> fin_cases j <;>\n"
                 "      norm_num [lower, pivots, rawGram, gramUpper, CurvatureWitness.alphaUpper, FrozenHessian.lppm,\n"
                 "        Fin.sum_univ_succ, Matrix.of_apply, Matrix.sub_apply, Matrix.smul_apply, Matrix.one_apply, Matrix.vecHead, Matrix.vecTail]\n"
                 "  · intro i\n    fin_cases i <;> norm_num [pivots]\n\n"
                 "end\nend Maxwell.Certificate.QuadraticWitness\n")
        emit(name, text, "psd")
    emit("Complete", """import Maxwell.Certificate.QuadraticWitness.ActionComplete
import Maxwell.Certificate.QuadraticWitness.Gram
import Maxwell.Certificate.QuadraticWitness.GramNorm
import Maxwell.Certificate.QuadraticWitness.GramRelative

#print axioms Maxwell.Certificate.QuadraticWitness.rawGram_binding
#print axioms Maxwell.Certificate.QuadraticWitness.gram_norm_psd
#print axioms Maxwell.Certificate.QuadraticWitness.gram_relative_psd
""", "final_audit")
    assert sha256(action_manifest.read_bytes()).hexdigest() == before
    result = {"action_manifest_sha256": before, "modules": modules, "dot_products": len(pairs),
              "summands_per_dot": 6000, "alpha_upper": str(alpha),
              "canonical_frozen_sha256": sha256(canonical_json.read_bytes()).hexdigest()}
    (ROOT / "evidence/quadratic_gram_manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    print(f"Generated {len(pairs)} distinct full quadratic Gram dot proofs and exact norm/relative LDL witnesses.")


if __name__ == "__main__":
    main()
