"""Freeze the other three L-point proposals and emit ordinary kernel checks.

The source arrays and Python arithmetic only propose witnesses. The emitted
Lean modules check every action coordinate, parity coordinate and squared-norm
sum, then bind the checks to the actual primitive electric Bloch operators.
This generator does not launch the numerical proof queue.
"""
from __future__ import annotations

from hashlib import sha256
import importlib.util
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / "certificates/yee/results/defects"
OUT = ROOT / "Maxwell/Certificate/OtherPointWitness"
EVIDENCE = ROOT / "evidence/other_point_witnesses"
BASE = "Maxwell.Certificate.OtherPointWitness"
POINTS = [("Lppp", "L+++", (1, 1, 1), -1),
          ("Lpmp", "L+-+", (1, 0, 1), 1),
          ("Lmpp", "L-++", (-1, 0, 0), 1)]


def vector(xs):
    return "![" + ", ".join(map(str, xs)) + "]"


def main():
    spec = importlib.util.spec_from_file_location("exact_edge_arithmetic", SOURCE / "exact_edge_arithmetic.py")
    arithmetic = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(arithmetic)
    material_file = SOURCE / "inversion_edge_material.json"
    point_witness_file = SOURCE / "make_inversion_point_witnesses.npz"
    witness_files = {stem: SOURCE / f"inversion_feshbach_{stem.lower()}.npz" for stem, _, _, _ in POINTS}
    material = json.loads(material_file.read_text())
    with np.load(point_witness_file, allow_pickle=False) as data:
        assert data["perturbation_numerators"].tolist() == material["full_conventional_perturbation_numerators"]
    vectors = {}
    for stem, label, _, _ in POINTS:
        with np.load(witness_files[stem], allow_pickle=False) as data:
            assert data["perturbation_numerators"].tolist() == material["full_conventional_perturbation_numerators"]
            vectors[label] = data["inversion_perturbed_eigenvectors"].copy()
    OUT.mkdir(parents=True, exist_ok=True)
    EVIDENCE.mkdir(parents=True, exist_ok=True)
    modules = [BASE + ".Sound"]
    receipts = []

    for stem, label, momentum, parity in POINTS:
        radius_bits = 44 if stem == "Lppp" else 47
        integer_exponent = 160 - 2 * radius_bits
        residual_lemma = "residual_bound44" if radius_bits == 44 else "residual_bound"
        folder = OUT / stem
        folder.mkdir(exist_ok=True)
        namespace = BASE + "." + stem
        k = vector(momentum)
        model = arithmetic.ExactFiber(momentum, material["full_conventional_perturbation_numerators"])
        proposals = [model.project(arithmetic.quantize(vectors[label][:, a]), parity) for a in range(2)]
        images = [model.apply_mass_scaled(v) for v in proposals]
        statistics = [model.eigen_residual(v) for v in proposals]

        def emit(name, imports, body, finite=False):
            source = "-- Generated by generate_other_point_witnesses.py; proposals require kernel checks.\n"
            source += "\n".join("import " + x for x in imports) + "\n\n"
            source += f"namespace {namespace}\n"
            source += "open Maxwell.Spectral Maxwell.Spectral.PrimitiveYee\n"
            source += "open Maxwell.Certificate.PrimitiveBinding\n"
            source += "open Maxwell.Certificate.PointWitness (integerVector squareNormI blockNormI)\n"
            source += "noncomputable section\n"
            if finite:
                source += "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n"
            source += body + f"\nend\nend {namespace}\n"
            (folder / (name + ".lean")).write_text(source)
            modules.append(namespace + "." + name)

        for a in range(2):
            for kind, values in [("Numerator", proposals[a]), ("Imagenumerator", images[a])]:
                name = ("numerator" if kind == "Numerator" else "imageNumerator") + str(a)
                body = []
                for d in range(3):
                    for x in range(20):
                        rows = [vector(int(values[d*2000+x*100+y*10+z]) for z in range(10)) for y in range(10)]
                        body.append(f"def {name}_{d}_{x} : Fin 10 → Fin 10 → ℤ := {vector(rows)}")
                rows = [vector(f"{name}_{d}_{x}" for x in range(20)) for d in range(3)]
                body.append(f"def {name} (e : Electric) : ℤ := ({vector(rows)}) e.1 e.2.1 e.2.2.1 e.2.2.2")
                emit(kind + str(a), ["Maxwell.Certificate.IntegerAction", "Maxwell.Certificate.PointWitness.NormDefs"], "\n".join(body), True)

            actions = []
            for d in range(3):
                for x in range(20):
                    name = f"Action{a}D{d}X{x:02}"
                    actions.append((name, d, x))
                    emit(name, [namespace + f".Numerator{a}", namespace + f".Imagenumerator{a}"],
                         f"theorem action{a}_{d}_{x:02} (y z : Fin 10) :\n"
                         f"    fiberActionI {k} numerator{a} ({d}, ({x}, y, z)) =\n"
                         f"      imageNumerator{a} ({d}, ({x}, y, z)) := by\n"
                         "  fin_cases y <;> fin_cases z <;> decide +kernel\n", True)
            body = (f"theorem numerator{a}_action (e : Electric) :\n"
                    f"    fiberActionI {k} numerator{a} e = imageNumerator{a} e := by\n"
                    "  rcases e with ⟨d, x, y, z⟩\n  fin_cases d <;> fin_cases x\n")
            body += "\n".join(f"  · exact action{a}_{d}_{x:02} y z" for _, d, x in actions)
            emit(f"Action{a}Complete", [namespace + "." + n for n, _, _ in actions], body)

            parities = []
            for x in range(20):
                name = f"Parity{a}X{x:02}"
                parities.append(name)
                emit(name, [namespace + f".Numerator{a}", "Maxwell.Certificate.InversionInteger"],
                     f"theorem parity{a}_{x:02} (d : Fin 3) (y z : Fin 10) :\n"
                     f"    electricInversionActionI {k} numerator{a} (d, ({x}, y, z)) =\n"
                     f"      ({parity} : ℤ) * numerator{a} (d, ({x}, y, z)) := by\n"
                     "  fin_cases d <;> fin_cases y <;> fin_cases z <;> decide +kernel\n", True)
            body = (f"theorem numerator{a}_parity (e : Electric) :\n"
                    f"    electricInversionActionI {k} numerator{a} e = ({parity} : ℤ) * numerator{a} e := by\n"
                    "  rcases e with ⟨d, x, y, z⟩\n  fin_cases x\n")
            body += "\n".join(f"  · exact parity{a}_{x:02} d y z" for x in range(20))
            emit(f"Parity{a}Complete", [namespace + "." + n for n in parities], body)

            stats = statistics[a]
            lam = stats["lambda_numerator"]
            residual = [w * 2**51 - lam*v for v, w in zip(proposals[a], images[a])]
            assert stats["residual_dyadic_exponent"] >= radius_bits
            assert model.invert(proposals[a]) == [parity*x for x in proposals[a]]
            for kind, values in [("Norm", proposals[a]), ("Residual", residual)]:
                blocks = [[sum(int(v)**2 for v in values[d*2000+x*100:d*2000+x*100+100]) for x in range(20)] for d in range(3)]
                total = sum(map(sum, blocks))
                name = kind.lower() + str(a)
                fun = f"numerator{a}" if kind == "Norm" else f"residual{a}"
                body = ""
                imports = [namespace + f".Numerator{a}", "Maxwell.Certificate.PointWitness.NormDefs"]
                if kind == "Residual":
                    imports.append(namespace + f".Imagenumerator{a}")
                    body += f"def lambdaNumerator{a} : ℤ := {lam}\n"
                    body += f"def residual{a} (e : Electric) : ℤ := imageNumerator{a} e * 2^51 - lambdaNumerator{a} * numerator{a} e\n"
                body += f"def {name}Blocks : Fin 3 → Fin 20 → ℤ := {vector(vector(row) for row in blocks)}\n"
                body += (f"theorem {name}Blocks_checked (d : Fin 3) (x : Fin 20) :\n"
                         f"    blockNormI {fun} d x = {name}Blocks d x := by\n"
                         "  fin_cases d <;> fin_cases x <;> decide +kernel\n"
                         f"theorem {name}_checked : squareNormI {fun} = {total} := by\n"
                         f"  unfold squareNormI\n  simp_rw [{name}Blocks_checked]\n  decide +kernel\n")
                emit(kind + str(a), imports, body, True)

            body = f"def pointVector{a} : EuclideanSpace ℂ Electric := integerVector numerator{a} (2^101)\n"
            body += f"def pointCenter{a} : ℝ := (lambdaNumerator{a} : ℝ) / 2^80\n"
            body += (f"theorem pointVector{a}_ne_zero : pointVector{a} ≠ 0 := by\n"
                     "  apply PointWitness.integerVector_ne_zero\n  · norm_num\n"
                     f"  · rw [norm{a}_checked]\n    norm_num\n"
                     f"theorem pointVector{a}_residual :\n"
                     f"    ‖OtherPointWitness.operator {k} pointVector{a} - (pointCenter{a} : ℂ) • pointVector{a}‖^2 ≤\n"
                     f"      ((1 : ℝ) / 2^{radius_bits})^2 * ‖pointVector{a}‖^2 := by\n"
                     f"  apply OtherPointWitness.{residual_lemma} {k} numerator{a} imageNumerator{a} lambdaNumerator{a}\n"
                     f"  · exact funext numerator{a}_action\n"
                     f"  · change squareNormI residual{a} ≤ 2^{integer_exponent} * squareNormI numerator{a}\n"
                     f"    rw [residual{a}_checked, norm{a}_checked]\n    decide +kernel\n"
                     f"theorem pointVector{a}_parity :\n"
                     f"    YeeInversion.electricIsometry {k} pointVector{a} = ({parity} : ℂ) • pointVector{a} := by\n"
                     f"  exact_mod_cast integerVector_parity {k} numerator{a} (2^101) ({parity}) numerator{a}_parity\n"
                     f"theorem pointCenter{a}_range :\n"
                     f"    239/25000 < pointCenter{a} - 1/2^{radius_bits} ∧ pointCenter{a} + 1/2^{radius_bits} < 957/100000 := by\n"
                     f"  norm_num [pointCenter{a}, lambdaNumerator{a}]\n"
                     f"theorem pointCenter{a}_above_selected :\n"
                     f"    PointWitness.pointCenter0 + 1/2^47 + 33/10^9 < pointCenter{a} - 1/2^{radius_bits} := by\n"
                     f"  norm_num [PointWitness.pointCenter0, PointWitness.lambdaNumerator0, pointCenter{a}, lambdaNumerator{a}]\n")
            emit(f"Computed{a}", [BASE + ".Sound", namespace + f".Action{a}Complete", namespace + f".Parity{a}Complete",
                                  namespace + f".Norm{a}", namespace + f".Residual{a}", "Maxwell.Certificate.PointWitness.Bounds0"], body)
            receipts.append({"point": label, "momentum_twice": list(momentum), "parity": parity, "column": a,
                             "lambda_numerator": lam, "norm_squared_numerator": stats["vector_norm_squared_numerator"],
                             "residual_squared_numerator": stats["residual_squared_numerator"],
                             "proposed_radius_exponent": radius_bits})

        body = f"abbrev pointOperator := OtherPointWitness.operator ({k} : Translation)\n"
        body += f"theorem pointOperator_symmetric : pointOperator.IsSymmetric := OtherPointWitness.operator_symmetric _\n"
        body += ("theorem two_verified_eigenvalues :\n"
                 "    ∃ i j : Fin (Module.finrank ℂ (EuclideanSpace ℂ Electric)), i ≠ j ∧\n"
                 f"      |pointOperator_symmetric.eigenvalues rfl i - pointCenter0| ≤ 1/2^{radius_bits} ∧\n"
                 f"      |pointOperator_symmetric.eigenvalues rfl j - pointCenter1| ≤ 1/2^{radius_bits} := by\n"
                 "  apply two_distinct_eigenvalues_of_disjoint_residuals pointOperator pointOperator_symmetric\n"
                 "    pointVector0 pointVector1 pointVector0_ne_zero pointVector1_ne_zero\n"
                 f"    pointCenter0 pointCenter1 (1/2^{radius_bits}) (1/2^{radius_bits})\n"
                 "  · positivity\n  · positivity\n"
                 "  · norm_num [pointCenter0, pointCenter1, lambdaNumerator0, lambdaNumerator1]\n"
                 "  · exact pointVector0_residual\n  · exact pointVector1_residual\n")
        body += ("theorem two_verified_positive_eigenvalues_above_selected :\n"
                 "    ∃ i j : Fin (Module.finrank ℂ (EuclideanSpace ℂ Electric)), i ≠ j ∧\n"
                 "      pointOperator_symmetric.eigenvalues rfl i ∈ Set.Ioo (239/25000) (957/100000) ∧\n"
                 "      pointOperator_symmetric.eigenvalues rfl j ∈ Set.Ioo (239/25000) (957/100000) ∧\n"
                 "      PointWitness.pointCenter0 + 1/2^47 + 33/10^9 < pointOperator_symmetric.eigenvalues rfl i ∧\n"
                 "      PointWitness.pointCenter0 + 1/2^47 + 33/10^9 < pointOperator_symmetric.eigenvalues rfl j := by\n"
                 "  obtain ⟨i, j, hij, hi, hj⟩ := two_verified_eigenvalues\n"
                 "  have hi' := abs_le.mp hi\n  have hj' := abs_le.mp hj\n"
                 "  refine ⟨i, j, hij, ?_, ?_, ?_, ?_⟩\n"
                 "  · constructor <;> linarith [pointCenter0_range.1, pointCenter0_range.2]\n"
                 "  · constructor <;> linarith [pointCenter1_range.1, pointCenter1_range.2]\n"
                 "  · linarith [pointCenter0_above_selected]\n"
                 "  · linarith [pointCenter1_above_selected]\n")
        emit("Verified", [namespace + ".Computed0", namespace + ".Computed1"], body)

    (EVIDENCE / "modules.json").write_text(json.dumps(modules, indent=2) + "\n")
    metadata = {"scope": "Proposals for six actual other-L point eigenvalue residuals; no numeric proof queue launched",
                "source_sha256": {p.name: sha256(p.read_bytes()).hexdigest() for p in
                                  [material_file, point_witness_file, *witness_files.values(), SOURCE / "exact_edge_arithmetic.py"]},
                "vector_basis": "Canonical Feshbach archives, shared with the actual corrector/Hessian/Gram pipeline",
                "points": receipts, "modules": len(modules),
                "action_coordinates": 36000, "parity_coordinates": 36000,
                "remaining_semantic_dependency": "Original-material cubic inertia transfer; residual inclusion alone does not establish complete-cluster exclusion."}
    (EVIDENCE / "proposals.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(f"Generated {len(modules)} modules for six vectors, 36000 action and 36000 parity coordinates. No kernel queue launched.")


if __name__ == "__main__":
    main()
