"""Independent integer geometry and exact rank-4 voxel coverage check.
Uses no imported supplied geometry/coverage implementation and no PASS strings.
The matrix certificates themselves are separately regenerated by reproduce_fixed_cover.py.
"""
from pathlib import Path
from fractions import Fraction as F
import itertools,json,hashlib,argparse

def geometry():
    P=20
    fcc=[(0,0,0),(0,80,80),(80,0,80),(80,80,0)]
    spheres=[tuple((u+s*20)%160 for u in x) for x in fcc for s in (-1,1)]
    high=set()
    for cell in itertools.product(range(P),repeat=3):
        point=tuple(8*x+4 for x in cell)
        if any(sum(min((x-y)%160,(y-x)%160)**2 for x,y in zip(point,c))<=1600 for c in spheres):
            high.add(cell)
    assert len(high)==3928
    for shift in [(0,10,10),(10,0,10),(10,10,0)]:
        assert {tuple((x+y)%20 for x,y in zip(p,shift)) for p in high}==high
    syms=[]
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((-1,1),repeat=3):
            candidates=[]
            for tr in itertools.product((0,5,10,15),repeat=3):
                mapped={tuple((signs[j]*(2*p[perm[j]]+1)+2*tr[j]-1)//2%20 for j in range(3)) for p in high}
                if mapped==high:candidates.append(tr)
            assert candidates
            syms.append([perm,signs,candidates[0]])
    edge_sums=set()
    for cell in itertools.product(range(P),repeat=3):
        for a in range(3):
            axes=[i for i in range(3) if i!=a];total=0
            for offsets in itertools.product((0,-1),repeat=2):
                nbr=list(cell)
                for axis,off in zip(axes,offsets):nbr[axis]=(nbr[axis]+off)%20
                total+=12 if tuple(nbr) in high else 1
            edge_sums.add(total)
    assert edge_sums=={4,15,26,37,48}
    return {"high_cells":len(high),"edge_average_numerators_over_4":sorted(edge_sums),"symmetries":syms}

def wedge_feasible_by_vertices(lo,hi):
    # Intersect nine halfspaces by enumerating every three-plane vertex.
    # The bounded box intersection is nonempty iff it has a vertex.
    # Coordinates scaled by 16, so wedge sum bound is 24.
    planes=[]
    for j in range(3):
        row=tuple(int(k==j) for k in range(3));planes.append((row,hi[j]));planes.append((tuple(-x for x in row),-lo[j]))
    planes.extend([((-1,1,0),0),((0,-1,1),0),((1,1,1),24)])
    def det(a):return a[0][0]*(a[1][1]*a[2][2]-a[1][2]*a[2][1])-a[0][1]*(a[1][0]*a[2][2]-a[1][2]*a[2][0])+a[0][2]*(a[1][0]*a[2][1]-a[1][1]*a[2][0])
    for chosen in itertools.combinations(planes,3):
        rows=[x[0] for x in chosen];b=[x[1] for x in chosen];d=det(rows)
        if d==0:continue
        x=[]
        for j in range(3):
            aa=[list(r) for r in rows]
            for i in range(3):aa[i][j]=b[i]
            x.append(F(det(aa),d))
        if all(sum(a[j]*x[j] for j in range(3))<=b for a,b in planes):return True
    return False

def coverage(path):
    obj=json.loads(path.read_text());records=obj["accepted"]
    boxes={}
    for r in records:
        c=list(map(F,r["center"]));h=F(r["halfwidth"]);assert h==F(1,32)
        lo=tuple((x-h)*16 for x in c);assert all(x.denominator==1 for x in lo)
        key=tuple(int(x) for x in lo);assert key not in boxes;boxes[key]=r
    needed=set();gamma=0;empty=0
    for lo in itertools.product(range(16),repeat=3):
        hi=tuple(x+1 for x in lo)
        if not wedge_feasible_by_vertices(lo,hi):empty+=1;continue
        if max(hi)<=3:gamma+=1;continue
        assert lo in boxes,("uncovered",lo)
        needed.add(lo)
    assert len(needed)==604
    return {"required_certified_boxes":len(needed),"finest_gamma_voxels":gamma,"empty_voxels":empty,"supplied_proposed_boxes":len(boxes),"required_witness_names":sorted(boxes[k]["witness"] for k in needed)}

def main():
    ap=argparse.ArgumentParser();ap.add_argument("--source",type=Path,required=True);ap.add_argument("--output",type=Path,required=True);args=ap.parse_args()
    out={"geometry":geometry(),"coverage":coverage(args.source/"cover_screen_complete.json")}
    args.output.write_text(json.dumps(out,indent=2)+"\n")
    print("Independent exact geometry, scalar averaging, all 48 symmetry actions, and complete rank-4 voxel coverage verified.")
    print("Required exact matrix certificates:",out["coverage"]["required_certified_boxes"])
if __name__=="__main__":main()
